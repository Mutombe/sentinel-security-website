# -*- coding: utf-8 -*-
"""Write assets/img/photos/CREDITS.md.

Three sources now, and which is which matters: Sentinel's own photography,
licensed stock the client supplied, and the Unsplash frames that remain for
hardware and places where nobody is in shot.

Run:  python tools/credits.py
"""
import io, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, os.pardir)
sys.path.insert(0, HERE)
from photos_local import LOCAL, PORTRAIT


def main():
    store = os.path.join(HERE, "photo_store.json")
    used = json.load(io.open(store, encoding="utf-8")).get("used", {}) \
        if os.path.exists(store) else {}
    by_file = {u["file"]: u for u in used.values()}

    client = {k for k, v in LOCAL.items() if v[0].startswith(("Sentinel", "176f250b"))}
    licensed = set(LOCAL) - client
    # The phone batch is the client's own too, but it arrived a different way
    # and is held at a different size, so it is listed on its own rather than
    # mixed in with the studio frames.
    phone = {k for k in client if LOCAL[k][3] is PORTRAIT}
    client -= phone
    rest = sorted(f for f in by_file if f not in LOCAL)

    L = ["# Photography credits", "",
         "Three sources, and which is which matters.", "",
         "## Sentinel's own", "",
         "Supplied by the client. Officers in Sentinel uniform at Sentinel sites.",
         "These are the frames the site leads with, and more of them is the single",
         "biggest improvement still available to it.", "",
         "| File | Source |", "|---|---|"]
    L += ["| `%s` | `%s` |" % (k, LOCAL[k][0]) for k in sorted(client)]

    L += ["", "### Taken on a phone, October 2026", "",
          "Sent over WhatsApp, so they arrive already compressed and only 810",
          "by 1080. That is why they are shown portrait at the size they were",
          "taken: a wide frame would mean inventing pixels. Staff, a site",
          "visit, a technician working, and the company's own signs where they",
          "ended up.", "",
          "| File | Source |", "|---|---|"]
    L += ["| `%s` | `%s` |" % (k, LOCAL[k][0]) for k in sorted(phone)]

    L += ["", "## Licensed stock, supplied by the client", "",
          "Used only where no Sentinel frame exists for the subject.", "",
          "| File | Source |", "|---|---|"]
    L += ["| `%s` | `%s` |" % (k, LOCAL[k][0]) for k in sorted(licensed)]

    L += ["", "## Unsplash", "",
          "Hardware and places, with nobody in frame. Used under the",
          "[Unsplash licence](https://unsplash.com/license).", "",
          "| File | Photographer | Photo |", "|---|---|---|"]
    for f in rest:
        u = by_file[f]
        L.append("| `%s` | [%s](%s?utm_source=sentinel&utm_medium=referral) | [link](%s) |"
                 % (f, u["by"], u["by_url"], u["html"]))

    L += ["", "Generated by `tools/credits.py`."]
    out = os.path.join(ROOT, "assets", "img", "photos", "CREDITS.md")
    io.open(out, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print("wrote CREDITS.md: %d Sentinel, %d licensed, %d Unsplash"
          % (len(client), len(licensed), len(rest)))


if __name__ == "__main__":
    main()
